  hideTab(inputId = "tabsetPanel1", target = "Sample Correlation")
  hideTab(inputId = "tabsetPanel1", target = "Differential Analysis")
  hideTab(inputId = "tabsetPanel1", target = "PCA")
  hideTab(inputId = "tabsetPanel1", target = "Heatmap")
  hideTab(inputId = "tabsetPanel1", target = "Single Gene Visualisations")
  hideTab(inputId = "tabsetPanel1", target = "Enrichment Analysis")
  hideTab(inputId = "tabsetPanel1", target = "ML Classification")
  shinyjs::hideElement(id = "selection-mainPanel_other")
  shinyjs::hideElement(id = "data_summary")
  shinyjs::hideElement(id = "div_sampleCorrelation_main_panel")
  shinyjs::hideElement(id = "PCA_main_panel_div")
  shinyjs::hideElement(id = "Significance_div")
  shinyjs::hideElement(id = "Heatmap_div")
  shinyjs::hideElement(id = "SingleGene_div")
  shinyjs::hideElement(id = "enrichment_div")

# Set Up ad Show user Landing page ----
  # Define the guide
  # Note do this in here to avoid setting a global upon close
  guide_welcome <- Cicerone$
    new(id = "guide",
        opacity = 0.9,
        padding = 10,
        keyboard_control = TRUE)$
    step(
      el = "start_tour",
      title = "Welcome to cOmicsArt!",
      position = "right-center",
      description = HTML("
      <div style='min-width: 300px; min-height: 150px; padding: 10px;'>
        <img src='Logo_cOmicsArt_clear.png' alt='cOmicsArt Logo' style='max-width:90%;'>
        <div style='font-size: 18px; margin-top: 10px;'>
          <p><i class='fas fa-question-circle'></i> Need help? Press the blue button</p>
          <p><i class='fas fa-rocket'></i> Want to start directly? Click 'Next'.</p>
            <div style='font-size: 14px; color: #777; margin-top: 15px;'>
              <p><input type='checkbox' id='set_cookie_checkbox'> Do not show next time (sets a cookie)</p>
            </div>
        </div>
      </div>
    ")
    )$
    step(
      el = "tabsetPanel1",
      title = "Welcome to cOmicsArt!",
      description = "You pressed next - redirection triggered",
    )
  
  # Check if the cookie is present and update the output
  # On page load, check if the cookie exists
  observe({
    shinyjs::runjs("
      if (!checkHasBeenBeforeCookie()) {
        Shiny.setInputValue('first_visit', true);
      } else {
        Shiny.setInputValue('first_visit', false);
      }
    ")
  })

  # If it is the user's first visit, start the guide
  observeEvent(input$first_visit, {
    # shinytest2 runs the app in test mode: skip the welcome tour there
    if (input$first_visit && !isTRUE(getShinyOption("testmode"))) {
      guide_welcome$init()$start()
    } else {
      showTab(inputId = "tabsetPanel1", target = "Data selection", select = TRUE)
    }
  })
  
  # Delete the cookie if the toggle input is checked
  observeEvent(input$set_cookie, {
      shinyjs::runjs("deleteCookie('hasBeenBefore')")
      showNotification("Cookie 'hasBeenBefore' deleted. Please refresh the page.")
  })

  # Start the tour when the "Start Tour" button is clicked
  observeEvent(input$start_tour, {
    print("Star Tour")
    shinyjs::runjs("document.querySelector('.driver-close-btn').click();")
    guide$init()$start()
  })

  observeEvent(input$guide_cicerone_next, {
    print("Next")
    shinyjs::runjs("document.querySelector('.driver-close-btn').click();")
    showTab(inputId = "tabsetPanel1",target = "Data selection",select = T)
  })
  
  observeEvent(input$GoToStartAnalysis, {
    guide_startDiscover$init()$start()
  })

  output$help_tab_info <- renderText({
    HTML(paste0(
    "Please select an image to display within the sidebar(left)<br>",
    "To confirm your selection click the button labelled 'GO show me help!' within the sidebar."
    ))
  })

  # Help tab: WelcomePage image rendering (reactive to width/height sliders)
  # Note: Show/hide logic now handled client-side by conditionalPanel in ui.R
  output$WelcomePage <- renderImage({
    req(input$ImageSelect == "WelcomePage")  # Only render when WelcomePage is selected
    list(
      src = "www/WelcomPage.png",
      contentType = "image/png",
      width = paste0(input$ImageWidth,"%"),
      height = input$ImageHeight
    )
  }, deleteFile = FALSE)

  # Help tab: Info text that updates based on selection
  output$help_tab_info <- renderText({
    if(input$ImageSelect == "WelcomePage") {
      HTML(paste0(
        "As you selected the WelcomePage on the <b>left</b>, you can see a screenshot of the WelcomePage below.<br>",
        "If you want to see the full documentation, click ",
        "<a href='https://icb-dcm.github.io/cOmicsArt/' target='_blank'>here</a>",
        ".<br>or click on the link on the top left of the screen 'Go To Documentation'.<br><br>",
        "Within cOmicsArt this box will display information depending on the current tab you are in.<br> A tab represents an analysis."
      ))
    } else if(input$ImageSelect == "nothing selected") {
      HTML(paste0(
        "You have selected 'nothing selected' - hence there is nothing to show<br>.",
        "Do you want to see something else? Try to select a different Image (Select Image) on the left!<br>",
        "Did you maybe just press the button?"
      ))
    } else {
      ""  # Empty for YouTube Tutorial
    }
  })

  observeEvent(input$NextPanel_tutorial,{
    showTab(inputId = "tabsetPanel1",target = "Data selection",select = T)
  })



# Init session-scoped reactiveValues (Phase 2 Refactoring) ----
  # Data objects storage
  session_data <- reactiveValues(
    # Primary data objects
    data = NULL,                        # Current processed data (main analysis object)
    data_original = NULL,               # Original uploaded data (preserved)
    data_batch_corrected = NULL,        # Batch-corrected data (optional)

    # DESeq2 objects
    DESeq_obj = NULL,                   # DESeq2 object (if vst_DESeq used)
    DESeq_obj_batch_corrected = NULL,   # Batch-corrected DESeq object

    # Console outputs (for display)
    batch_console_output = NULL,        # Batch correction console output
    batch_warnings = NULL,              # Batch correction warnings
    all_console_output = NULL,          # All preprocessing output
    all_warnings = NULL,                # All preprocessing warnings

    # Module-specific state storage (session-level for code generation)
    # NOTE: Kept at session level to support R code generation
    Heatmap = NULL,
    SampleCorrelation = NULL,
    SigAna = NULL,
    SingleGeneVis = NULL
  )

  # Parameters and configuration storage
  session_params <- reactiveValues(
    # Data type and organism
    omic_type = NULL,                   # "Transcriptomics", "Proteomics", etc.
    organism = NULL,                    # For biomaRt annotation
    addedGeneAnno = FALSE,              # Gene annotation added flag

    # Preprocessing configuration
    preprocessing_procedure = NULL,     # "vst_DESeq", "limma_voom", etc.
    preprocessing_filtering = NULL,     # Filtering method
    BatchColumn = "NULL",               # Batch effect column name

    # Filtering parameters
    filter_threshold = NULL,            # Main filtering threshold
    filter_threshold_samplewise = NULL, # Sample-wise threshold
    filter_samplesize = NULL,           # Filter sample size

    # DESeq2 parameters
    deseq_formula = NULL,               # DESeq2 formula string
    deseq_factors = NULL,               # DESeq2 factors vector
    DESeq_formula_batch = NULL,         # Formula including batch

    # Limma voom parameters
    limma_intercept = NULL,             # Limma intercept
    limma_formula = NULL,               # Limma formula

    # Selection parameters (standardized names)
    selected_rows = NULL,               # Chosen entity annotation values (select_data() argument)
    selected_samples = NULL,            # Chosen sample annotation values (select_data() argument)
    rows_selected = NULL,               # Selected row IDs
    samples_selected = NULL,            # Selected sample IDs
    row_type = NULL,                    # Row selection type
    sample_type = NULL,                 # Sample selection type

    # Visualization parameters
    violin_color = NULL,                # Violin plot color preference

    # Module-specific parameters (session-level for code generation)
    Enrichment = list(),                # Enrichment analysis params (nested)
    Heatmap = NULL,                     # Heatmap params
    SigAna = NULL,                      # Significance analysis params
    SingleGeneVis = NULL                # Single gene visualization params
  )

  # Session cleanup: reactiveValues auto-cleanup on session end
  # Only need to remove the www/ folder
  session$onSessionEnded(function() {
    # Delete the folder with the session token
    if(dir.exists(paste0("www/",session$token))){
      # Remove the directory and its contents
      unlink(paste0("www/",session$token), recursive = TRUE)
      if (!dir.exists(paste0("www/",session$token))) {
        cat("Session cleanup: Directory successfully removed.\n")
      } else {
        cat("Session cleanup: Directory could not be removed.\n")
      }
    }
  })
# Init update Object ----
  # updating is a reative value that counts up whenever data is updated
  # this is used to trigger the update of the servers
  updating <- reactiveValues(count = 0)
## Quit App Button ----
  observeEvent(input$Quit_App,{
    showModal(
      modalDialog(
        tags$h4('You can download the complete report by clicking on the link'),
        footer=tagList(
          a(
            href="Report.html", 
            "Download report", 
            download=NA, 
            target="_blank"
          ),
          actionButton(
            inputId = "Done",
            label = "Done"
          ),
          modalButton('Cancel')
        )
      )
    )
  })
  
  observeEvent(input$Done,{
    removeModal()
    show_toast(
      title = "Good Bye!",
      type = "success",
      position = "top",
      timerProgressBar = FALSE,
      width = "100%"
      )
    session$close()
  })
  
# Upload ----
  upload <- upload_server("upload")
  data_input_shiny <- upload$done

## Bridge (temporary, removed in Phase 3h) ----
  # writes the Upload where the rest of the app reads it
  observeEvent(upload$done(), {
    session_data$data_original <- upload$raw()
    session_data$data <- upload$dataset_copy()
    session_params$addedGeneAnno <- upload$added_gene_anno()
    # Count up updating
    updating$count <- updating$count + 1
    # Show the Selection controls and the Pre-processing tab
    shinyjs::showElement("selection-mainPanel_other")
    if(upload$source() != "testdata"){
      showTab(inputId = "tabsetPanel1", target = "Pre-processing")
    }
  })
  observeEvent(upload$omic_type(), {
    session_params$omic_type <- upload$omic_type()
  })
  # gene annotation edits the raw object
  observeEvent(upload$annotated(), {
    session_data$data_original <- upload$raw()
    session_data$data <- fill_na_row_annotation(session_data$data)
    session_params$addedGeneAnno <- upload$added_gene_anno()
    session_params$organism <- upload$organism()
  })
  observeEvent(upload$cleared(), {
    # as before the first Upload: no Selection controls, no Pre-processing tab
    shinyjs::hideElement("selection-mainPanel_other")
    hideTab(inputId = "tabsetPanel1", target = "Pre-processing")
    hide_tabs()
  })

## Plots
  output$raw_violin_plot <- renderPlot({
    req(able_to_plot())
    req(react_violin_plot_raw())
    react_violin_plot_raw()
  })
  output$preprocessed_violin_plot <- renderPlot({
    req(able_to_plot())
    req(react_violin_plot())
    react_violin_plot()
  })
  output$mean_sd_plot <- renderPlot({
    req(able_to_plot())
    req(react_mean_sd_plot())
    react_mean_sd_plot()
  })

## Set reactiveVals ----
  react_violin_plot <- reactiveVal(NULL)
  react_violin_plot_raw <- reactiveVal(NULL)
  react_mean_sd_plot <- reactiveVal(NULL)
  able_to_plot <- reactiveVal(FALSE)

  observeEvent(input$console_toggle_button, {
    shinyjs::toggle(id = "console_toggle")
  })

# Selection ----
  selection <- selection_server(
    "selection",
    raw = reactive(session_data$data_original),
    upload_done = data_input_shiny
  )

## Bridge (temporary) ----
  # writes the Selection where the rest of the app reads it; only when it is
  # confirmed or Pre-processing starts, so it never replaces processed data
  write_selection <- function(){
    current <- isolate(selection$selected())
    session_data$data <- current$data
    params <- selection_params(current)
    for (name in names(params)) session_params[[name]] <- params[[name]]
  }
  # "Go to Preprocessing" / "Start the Journey": report lines, then Pre-processing
  observeEvent(selection$confirmed(),{
    able_to_plot(FALSE)
    # Do actual selection before logging
    write_selection()
    chosen <- selection$inputs()
    # add row and col selection options
    fun_LogIt(session, message = "**DataSelection** - The following selection was conducted:")
    fun_LogIt(session, message = paste0(
      "**DataSelection** - Samples:\n\t DataSelection - based on: ",
      chosen$sample_type,": ",
      paste(chosen$sample_selection,collapse = ", ")
    ))
    fun_LogIt(session, message = paste0(
      "**DataSelection** - Entities:\n\t DataSelection - based on: ",
      chosen$row_type,
      ": ",paste(chosen$row_selection,collapse = ", ")
    ))
    
    fun_LogIt(session, message = "### Publication Snippet")
    fun_LogIt(session, message = snippet_dataInput(
      data=reactiveValuesToList(session_data),
      params=reactiveValuesToList(session_params)
    ))
    fun_LogIt(session, message = "<br>")
    showTab(inputId = "tabsetPanel1",target = "Pre-processing",select = T)
  })
  
# Pre-processing after Selection ----
# Set Selected Data as Head to allow reiteration of pre-processing

## UI section ----
  # Dynamically update second dropdown based on Processing Type
  output$dynamic_options_ui <- renderUI({
    req(input$processing_type)  # Ensure input exists
    choices <- procedure_choices(input$processing_type)
    tagList(
    if(choices$filtering){
      div(style = "margin-left: 15px;",
          selectInput(
            inputId = "PreProcessing_Procedure_filtering",
            label = "Choose Filtering",
            choices = c("global Filtering" = "filterOnly",
                        "sample-wise Filtering" = "filterPerSample"),
            selected = NULL,
            multiple = FALSE
          )
      )
    },
    div(style = "margin-left: 15px;",
      selectInput(
        inputId = "PreProcessing_Procedure",
        label = "Choose Processing Option",
        choices = choices$procedures,
        selected = NULL,
        multiple = FALSE
      )
    )
    )
  })
  # Show additional numeric input if "Omic-specific filtering" is chosen
  output$additional_inputs_filter_ui <- renderUI({
    req(input$PreProcessing_Procedure)
    print(input$PreProcessing_Procedure)
    filter <- filter_inputs(
      input$PreProcessing_Procedure, input$PreProcessing_Procedure_filtering,
      upload$omic_type(), ncol(session_data$data)
    )
    if (is.null(filter)) return(NULL)
    if (filter$kind == "global") {
      tagList(
        div(style = "margin-left: 30px;",
          numericInput(
            inputId = "filter_threshold",
            label = "Specifcy the minimum sum of counts/concentration accross all samples for an entitie to be kept in the analysis.",
            value = filter$threshold,
            min = 0
          )
        )
      )
    } else {
      tagList(
        div(style = "margin-left: 30px;",
        numericInput(
            inputId = "filter_threshold_samplewise",
            label = "Specifcy theFiltering threshold of counts/concentration for an entitie",
            value = filter$threshold
          ),
        numericInput(
            inputId = "filter_samplesize",
            label = "Number of Samples that need to pass the Filtering threshold",
            value = filter$samplesize,
            min = 1,
            max = filter$max_samplesize,
            step = 1
          ),
        helpText(paste0("Note: This number should not exceed ", filter$max_samplesize, "(the number of samples in your data set)")
        )
        )
      )
    }
  })

  # Update the batch effect UI based on the available columns
  output$batch_effect_ui <- renderUI({
    req(data_input_shiny())
    selectInput(
      inputId = "BatchEffect_Column",
      label = "[optional] Select Batch Effect Column",
      choices = batch_column_choices(
        session_data$data_original, input$PreProcessing_Procedure, input$DESeq_formula_sub
      ),
      selected = "NULL"
    )
  })
  output$formula_sub_ui <- renderUI({
    req(data_input_shiny())
    req(input$PreProcessing_Procedure)
    design <- design_inputs(session_data$data, input$PreProcessing_Procedure)
    if (is.null(design)) return(NULL)
    if(design$kind == "deseq"){
      div(style = "margin-left: 30px;",
        selectInput(
          inputId = "DESeq_formula_sub",
          label = paste0(
            "Choose factors to account for ",
            "(App might crash if your factor has only 1 sample per level)"
          ),
          choices = design$choices,
          multiple = T,
          selected = design$selected
        )) %>% helper(type = "markdown", content = "PreProcessing_DESeq")
    }else{
      div(style = "margin-left: 30px;",
        tagList(
          # add a radiobutton whether one wants an intercept or not
          radioButtons(
            inputId = "limma_intercept",
            label = "Include Intercept?",
            choices = c("Yes" = "TRUE", "No" = "FALSE"),
            selected = "TRUE"
          ),
        selectInput(
          inputId = "limma_formula",
          label = paste0(
            "Choose the design formula for limma voom"
          ),
          choices = design$choices,
          multiple = T,
          selected = design$selected
        ) %>% helper(type = "markdown", content = "PreProcessing_voom")
        )
      )
    }
  })

  output$Statisitcs_Data <- renderText({
    "Press 'Get-Preprocessing' to start!"
  })
  output$raw_violin_plot <- renderPlot({
    req(able_to_plot())
    violin_plot(
      session_data$data_original[session_params$rows_selected, session_params$samples_selected],
      violin_color = isolate(input$violin_color)
    )
  })
  output$preprocessed_violin_plot <- renderPlot({
    req(able_to_plot())
    violin_plot(session_data$data, violin_color = input$violin_color)
  })

## Preprocessing ----
  selectedData_processed <- eventReactive(input$Do_preprocessing,{
    # only enter this when you actually click data
    req(input$Do_preprocessing > 0)
    shinyjs::showElement(id = "data_summary")
    waiter <- Waiter$new(
      html = LOADING_SCREEN,
      color = "#3897F147",
      hide_on_render = FALSE

    )
    waiter$show()
    write_selection()
    print("Starting the Preprocessing")
    # ---- Value Assignment and Parameter Saving for later use ----
    options <- preprocessing_options(
      procedure = input$PreProcessing_Procedure,
      filtering = input$PreProcessing_Procedure_filtering,
      batch_column = input$BatchEffect_Column,
      deseq_factors = input$DESeq_formula_sub,
      filter_threshold = input$filter_threshold,
      filter_threshold_samplewise = input$filter_threshold_samplewise,
      filter_samplesize = input$filter_samplesize,
      limma_intercept = input$limma_intercept,
      limma_formula = input$limma_formula
    )
    rows_selected <- session_params$rows_selected
    samples_selected <- session_params$samples_selected
    params <- preprocessing_params(options)
    for (name in names(params)) session_params[[name]] <- params[[name]]

    # reset data to the selection that was done, then pre-process
    res <- tryCatch(
      run_preprocessing(
        data = session_data$data_original[rows_selected, samples_selected],
        omic_type = session_params$omic_type,
        options = options
      ),
      preprocessing_error = function(e){
        if (e$step == "normality") {
          output$Statisitcs_Data <- renderText({ERROR_NORM_TEST})
        } else {
          if (e$step == "empty") {
            error_modal(conditionMessage(e))
          } else if (e$step == "batch") {
            error_modal(e$parent, additional_text = ifelse(
              options$procedure == "vst_DESeq", ERROR_BATCH_DESEQ, ERROR_BATCH_CORR
            ))
          } else {
            error_modal(e$parent)
          }
          output$Statisitcs_Data <- renderText({ERROR_PREPROC})
          hide_tabs()
        }
        waiter$hide()
        req(FALSE)
      }
    )
    data <- res$data
    for (name in names(res$params)) session_params[[name]] <- res$params[[name]]
    if (options$procedure == "vst_DESeq") {
      session_data$DESeq_obj <- res$DESeq_obj
      session_data$DESeq_obj_batch_corrected <- res$DESeq_obj_batch_corrected
    }
    session_data$data_batch_corrected <- res$data_batch_corrected
    session_data$batch_console_output <- res$batch_console_output
    session_data$batch_warnings <- res$batch_warnings
    session_data$all_console_output <- res$console_output
    session_data$all_warnings <- res$warnings

    # assign session_data finally
    session_data$data <- data

    hasConsoleOutput <- reactive({
      # Check if we have output to display, regardless of current input values
      # Check for console output or warnings
      has_console <- !is.null(session_data$all_console_output) &&
        length(session_data$all_console_output) > 0

      has_warnings <- !is.null(session_data$all_warnings) &&
        length(session_data$all_warnings) > 0

      return(has_console || has_warnings)
    })
    observe({
      if(hasConsoleOutput()) {
        shinyjs::show("console_toggle_button")
      } else {
        shinyjs::hide("console_toggle_button")
      }
    })

    output$consoleOutputDisplay <- renderUI({
      # Check if we have output to display
      hasOutput <- FALSE
      hasConsoleOutput <- FALSE
      hasWarnings <- FALSE

      # Check for console output
      if (!is.null(session_data$all_console_output) &&
          length(session_data$all_console_output) > 0) {
        hasOutput <- TRUE
        hasConsoleOutput <- TRUE
      }

      # Check for warnings
      if (!is.null(session_data$all_warnings) &&
          length(session_data$all_warnings) > 0) {
        hasOutput <- TRUE
        hasWarnings <- TRUE
      }

      # Only show if we have output
      if (hasOutput) {
        tagList(
          div(
            class = "console-output-container",
            if (hasConsoleOutput) {
              tagList(
                h4("Console Output:"),
                tags$pre(paste(session_data$all_console_output, collapse = "\n"))
              )
            },
            if (hasWarnings) {
              tagList(
                h4("Warnings and Messages:"),
                tags$pre(paste(session_data$all_warnings, collapse = "\n"))
              )
            }
          )
        )
      } else {
        NULL  # Return nothing if conditions are not met
      }
    })

    show_tabs()
    
    # Count up updating
    updating$count <- updating$count + 1

    output$Statisitcs_Data <- renderText({
      shinyjs::click("SignificanceAnalysis-refreshUI",asis = T)
      shinyjs::click("single_gene_visualisation-refreshUI",asis = T)
      shinyjs::click("EnrichmentAnalysis-refreshUI",asis = T)
